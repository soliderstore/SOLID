CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 user_id INT UNSIGNED NOT NULL,
 request_key VARCHAR(64) NOT NULL,
 customer LONGTEXT NOT NULL,
 items LONGTEXT NOT NULL,
 subtotal_cents BIGINT UNSIGNED NOT NULL,
 discount_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
 total_cents BIGINT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY user_request (user_id, request_key),
 KEY orders_status_created (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
